import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { rolldown } from "rolldown";
import {
  SDK_COLLECT,
  SDK_PACKAGES,
} from "../packages/factory/deployer/sdk.ts";

const root = resolve(import.meta.dirname, "..");
const deployerDir = join(root, "packages", "factory", "deployer");

/** The workspace directory of each package, by name. */
const packageDirs = Object.fromEntries(
  ["factory", "github", "claude", "droid", "slack"].map((dir) => {
    const path = join(root, "packages", dir);
    const { name } = JSON.parse(readFileSync(join(path, "package.json"), "utf8"));
    return [name as string, path];
  }),
);

/** The file of a package's `factory-outpost` export, or of its default export. */
const outpostEntry = (name: string) => {
  const dir = packageDirs[name];
  if (!dir) throw new Error(`${name} isn't a workspace package`);
  const { exports } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const main = exports["."];
  return join(dir, typeof main === "string" ? main : (main["factory-outpost"] ?? main.default));
};

const input = {
  ...Object.fromEntries(
    Object.entries(SDK_PACKAGES).map(([name, module]) => [module, outpostEntry(name)]),
  ),
  [SDK_COLLECT]: join(deployerDir, "collect.ts"),
};

// One build with shared chunks, so that the config and the collector use the
// same instance of `@notation/resource`.
const bundle = await rolldown({
  input,
  platform: "neutral",
  // The root tsconfig maps each package to its full entry, which would win over
  // the `factory-outpost` condition.
  tsconfig: false,
  resolve: {
    conditionNames: ["factory-outpost", "import", "default"],
    mainFields: ["module", "main"],
  },
});
const { output } = await bundle.generate({
  format: "esm",
  entryFileNames: "[name].js",
  chunkFileNames: "[name]-[hash].js",
});
await bundle.close();

const files = Object.fromEntries(
  output.flatMap((file) => (file.type === "chunk" ? [[file.fileName, file.code]] : [])),
);
writeFileSync(
  join(deployerDir, "sdk.gen.ts"),
  `/** The modules that an outpost's config can import. Generated by \`pnpm build:sdk\`. */\nexport default ${JSON.stringify(files)} as Record<string, string>;\n`,
);
const size = Object.values(files).reduce((sum, code) => sum + code.length, 0);
console.log(`sdk.gen.ts: ${Object.keys(files).length} modules, ${Math.round(size / 1024)} KB`);
