import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { rolldown } from "rolldown";

const root = resolve(import.meta.dirname, "..");
const workersDir = join(root, "packages", "cloudflare", "workers");
const runner = readFileSync(join(root, "packages", "factory", "runner", "index.ts"), "utf8");

const RUNNER_MODULE = "factory:runner";

// The deployer commits the bundle to each outpost's Artifacts repo, and
// Workers Builds deploys it without bundling it again.
const bundle = await rolldown({
  input: join(workersDir, "outpost.ts"),
  platform: "neutral",
  tsconfig: false,
  external: [/^cloudflare:/, /^node:/],
  resolve: { conditionNames: ["workerd", "worker", "import", "default"], mainFields: ["module", "main"] },
  plugins: [
    {
      name: "factory-runner",
      resolveId: (id) => (id === RUNNER_MODULE ? id : null),
      load: (id) => (id === RUNNER_MODULE ? `export default ${JSON.stringify(runner)};` : null),
    },
  ],
});
const { output } = await bundle.generate({ format: "esm", codeSplitting: false });
await bundle.close();

const code = output[0].code;
writeFileSync(
  join(workersDir, "outpost.gen.ts"),
  `/** The outpost Worker's bundle. Generated by \`pnpm build:outpost\`. */\nexport default ${JSON.stringify(code)};\n`,
);
console.log(`outpost.gen.ts: ${Math.round(code.length / 1024)} KB`);
