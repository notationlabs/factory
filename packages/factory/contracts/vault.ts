import type { ResourceGroup } from "@notation/resource";
import type { Source } from "@notation/std/sources";
import * as v from "valibot";

/** A hub Worker or service that binds secrets from the vault. */
export type SecretConsumer = "router" | "deployer";

/**
 * Where a secret's value comes from: a Notation source and the key it is
 * asked for, such as `{ source: env, key: "CLAUDE_CODE_OAUTH_TOKEN" }`.
 * Without a source, deploy asks for the value when it creates the secret,
 * and `notation secret set <id>` sets it.
 */
export type SecretValueFrom =
  | { source: Source; key: string }
  | { source?: undefined; key?: undefined };

const isSource = (value: unknown): value is Source =>
  typeof value === "object" &&
  value !== null &&
  typeof (value as Source).name === "string" &&
  typeof (value as Source).has === "function" &&
  typeof (value as Source).get === "function";

/** Validates a `SecretValueFrom` in a group's config. */
export const secretValueFrom = v.union([
  v.object({
    source: v.custom<Source>(isSource, "source must be a Notation source"),
    key: v.string(),
  }),
  v.object({
    source: v.optional(v.undefined()),
    key: v.optional(v.undefined()),
  }),
]);

export type VaultSecretOptions = SecretValueFrom & {
  /**
   * Keys the secret in state, and is what `notation secret set <id>` takes.
   * The name in the store is generated by the vault's provider.
   */
  id: string;
  /**
   * The env var name that each consumer reads the secret as, such as
   * `FACTORY_ROOT_KEY`.
   */
  binding: string;
  /**
   * The hub Workers or services that bind the secret. Bind each secret to
   * as few as need it: the router never binds an account's secrets, and the
   * deployer never binds a connection's credentials.
   */
  consumers: SecretConsumer[];
};

/**
 * A secret in a vault. A provider's vault returns a subtype that holds its
 * own resources, which its Workers or services bind.
 */
export type VaultSecret = {
  readonly id: string;
  readonly binding: string;
  readonly consumers: readonly SecretConsumer[];
};

/**
 * The hub's write-only secret store. `secret()` declares a secret that the
 * vault owns. `bindings(consumer)` lists the secrets that the consumer binds.
 */
export interface Vault<S extends VaultSecret = VaultSecret>
  extends ResourceGroup {
  readonly provider: string;
  secret(opts: VaultSecretOptions): S;
  /**
   * The secrets that `consumer` binds. Secrets are declared by groups that
   * are made after the consumer, such as connections and the deployer's
   * accounts, so the list is only complete when evaluation ends. Read it
   * lazily, such as in a Worker's `bindings` function or in `onEvaluationEnd`.
   */
  bindings(consumer: SecretConsumer): S[];
}
